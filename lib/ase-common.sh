ase_can_prompt() {
  [[ -t 0 ]] && return 0
  [[ -r /dev/tty && -w /dev/tty ]]
}

ase_prompt_yn() {
  local question=$1
  local default=${2:-n}
  local hint answer
  if [[ $default == y ]]; then
    hint="[Y/n]"
  else
    hint="[y/N]"
  fi
  while true; do
    if [[ -t 0 ]]; then
      read -r -p "$question $hint " answer || true
    elif [[ -r /dev/tty ]]; then
      read -r -p "$question $hint " answer </dev/tty || true
    else
      return 1
    fi
    answer=${answer:-$default}
    case ${answer,,} in
      y | yes) return 0 ;;
      n | no) return 1 ;;
      *) echo "ase: 请输入 y 或 n。" >&2 ;;
    esac
  done
}

ase_hub_script_git_path() {
  local basename=$1
  local rel="${ASE_GIT_SCRIPTS_REL:-script-hub}"
  if [[ -n $rel ]]; then
    echo "${rel}/${basename}"
  else
    echo "$basename"
  fi
}

ase_fuzzy_match_names() {
  local query=$1
  shift
  local name qlower nlower
  qlower=${query,,}
  [[ -n $qlower ]] || return 0
  for name; do
    nlower=${name,,}
    if [[ $nlower == *"$qlower"* ]]; then
      printf '%s\n' "$name"
    fi
  done
}

ase_git_path_in_repo() {
